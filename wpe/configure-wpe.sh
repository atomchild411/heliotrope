#!/bin/sh
# Spike: cross-configure WPE WebKit 2.52.6 for IRIX 6.5 n32 (Cairo, CLoop,
# WPEPlatform headless + our own X11 view later). Run from scratch/wpe.
set -e
WS=/Volumes/portable/workspace-claude/IRIX
S=$WS/scratch/pkgsrc-irix/destdir
export PATH=$WS/scratch/pkgsrc-irix/host/bin:$PATH
export PKG_CONFIG_LIBDIR=$S/opt/pkgsrc/lib/pkgconfig:$S/opt/pkgsrc/share/pkgconfig
export PKG_CONFIG_SYSROOT_DIR=$S
unset PKG_CONFIG_FDO_SYSROOT_RULES
cmake -G Ninja -S wpewebkit-2.52.6 -B wpe-build \
  -DCMAKE_TOOLCHAIN_FILE=$WS/code/llvm-wt/iris-main/llvm/cmake/platforms/IRIX.cmake \
  -DIRIX_SYSROOT=$S -DIRIX_TOOLCHAIN=$WS/scratch/llvm-irix/cross21 -DIRIX_TUNE=r10000 \
  -DCMAKE_PREFIX_PATH=/opt/pkgsrc -DCMAKE_INSTALL_PREFIX=/opt/pkgsrc -DCMAKE_BUILD_TYPE=Release \
  -DPORT=WPE -DUSE_SKIA=OFF -DENABLE_JIT=OFF -DENABLE_C_LOOP=ON -DUSE_SYSTEM_MALLOC=ON \
  -DENABLE_WEBASSEMBLY=OFF -DENABLE_SAMPLING_PROFILER=OFF -DDEVELOPER_MODE=OFF \
  -DENABLE_WPE_PLATFORM=ON -DENABLE_WPE_PLATFORM_HEADLESS=ON -DENABLE_WPE_PLATFORM_DRM=OFF \
  -DENABLE_WPE_PLATFORM_WAYLAND=OFF -DENABLE_WPE_LEGACY_API=OFF -DENABLE_WPE_QT_API=OFF \
  -DENABLE_DOCUMENTATION=OFF -DENABLE_INTROSPECTION=OFF -DENABLE_JOURNALD_LOG=OFF \
  -DENABLE_BUBBLEWRAP_SANDBOX=OFF -DENABLE_GAMEPAD=OFF -DENABLE_GPU_PROCESS=OFF \
  -DENABLE_VIDEO=OFF -DENABLE_WEB_AUDIO=OFF -DENABLE_MEDIA_STREAM=OFF -DENABLE_WEB_RTC=OFF \
  -DENABLE_WEB_CODECS=OFF -DENABLE_MEDIA_RECORDER=OFF -DENABLE_ENCRYPTED_MEDIA=OFF \
  -DENABLE_SPEECH_SYNTHESIS=OFF -DENABLE_XSLT=OFF -DENABLE_WEBDRIVER=OFF -DENABLE_MINIBROWSER=OFF \
  -DENABLE_API_TESTS=OFF -DENABLE_LAYOUT_TESTS=OFF -DENABLE_REMOTE_INSPECTOR=OFF \
  -DUSE_ATK=OFF -DUSE_GBM=OFF -DUSE_LIBDRM=OFF -DUSE_LIBBACKTRACE=OFF -DUSE_LIBHYPHEN=OFF \
  -DUSE_AVIF=OFF -DUSE_JPEGXL=OFF -DUSE_LCMS=OFF -DUSE_WOFF2=OFF -DUSE_FLITE=OFF \
  -DUSE_SYSPROF_CAPTURE=OFF -DUSE_GSTREAMER=OFF -DENABLE_WEBGL=OFF \
  "-DCMAKE_CXX_FLAGS_RELEASE=-O2 -DNDEBUG -ffile-prefix-map=$PWD/= -isystem $S/opt/pkgsrc/include/gettext" \
  "-DCMAKE_C_FLAGS_RELEASE=-O2 -DNDEBUG -ffile-prefix-map=$PWD/= -isystem $S/opt/pkgsrc/include/gettext" \
  -DCMAKE_EXE_LINKER_FLAGS="-static-libstdc++ -Wl,-rpath,/opt/pkgsrc/lib -L$S/opt/pkgsrc/lib -lintl" \
  -DCMAKE_SHARED_LINKER_FLAGS="-static-libstdc++ -Wl,-rpath,/opt/pkgsrc/lib -L$S/opt/pkgsrc/lib -lintl" \
  "$@"
